create table public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number bigint generated by default as identity (start with 100001) unique,
  customer_id uuid references public.customers(id) on delete set null,
  guest_checkout boolean not null default false,
  contact_name text not null,
  contact_email extensions.citext,
  contact_phone text not null,
  contact_whatsapp text,
  status public.order_status not null default 'pending_verification',
  verification_status public.verification_status not null default 'pending',
  cod_settlement_status public.cod_settlement_status not null default 'not_due',
  currency char(3) not null default 'PKR' check (currency = 'PKR'),
  subtotal_pkr bigint not null check (subtotal_pkr >= 0),
  discount_pkr bigint not null default 0 check (discount_pkr >= 0),
  shipping_pkr bigint not null default 0 check (shipping_pkr >= 0),
  tax_pkr bigint not null default 0 check (tax_pkr >= 0),
  total_pkr bigint not null check (total_pkr >= 0),
  shipping_rule_id uuid references public.shipping_rules(id) on delete set null,
  discount_id uuid references public.discounts(id) on delete set null,
  idempotency_key text not null unique,
  customer_note text,
  internal_note text,
  placed_at timestamptz not null default timezone('utc', now()),
  confirmed_at timestamptz,
  cancelled_at timestamptz,
  delivered_at timestamptz,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  check (customer_id is not null or guest_checkout),
  check (discount_pkr <= subtotal_pkr),
  check (total_pkr = greatest(0::bigint, subtotal_pkr - discount_pkr + shipping_pkr + tax_pkr))
);
create index orders_customer_created_idx on public.orders(customer_id, created_at desc) where customer_id is not null;
create index orders_status_created_idx on public.orders(status, created_at desc);
create index orders_verification_status_idx on public.orders(verification_status, created_at desc);
create index orders_cod_status_idx on public.orders(cod_settlement_status, created_at desc);
create index orders_phone_idx on public.orders(contact_phone);

