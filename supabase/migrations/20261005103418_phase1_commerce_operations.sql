create table public.discounts (
  id uuid primary key default gen_random_uuid(),
  code extensions.citext not null unique,
  name text not null,
  description text,
  discount_type public.discount_type not null,
  percentage_bps integer check (percentage_bps is null or percentage_bps between 1 and 10000),
  fixed_amount_pkr bigint check (fixed_amount_pkr is null or fixed_amount_pkr > 0),
  max_discount_pkr bigint check (max_discount_pkr is null or max_discount_pkr > 0),
  min_order_pkr bigint not null default 0 check (min_order_pkr >= 0),
  usage_limit integer check (usage_limit is null or usage_limit > 0),
  usage_limit_per_customer integer check (usage_limit_per_customer is null or usage_limit_per_customer > 0),
  starts_at timestamptz,
  ends_at timestamptz,
  is_active boolean not null default true,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  check (ends_at is null or starts_at is null or ends_at > starts_at),
  check (
    (discount_type = 'percentage' and percentage_bps is not null and fixed_amount_pkr is null)
    or (discount_type = 'fixed_amount' and fixed_amount_pkr is not null and percentage_bps is null)
    or (discount_type = 'free_shipping' and percentage_bps is null and fixed_amount_pkr is null)
  )
);

